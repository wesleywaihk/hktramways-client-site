import { Direction } from "@/consts";
import stationsData from "./stations.json";

export type StationType = "STATION" | "TERMINUS";

export type StationDirection =
  "Eastbound" | "Westbound" | "Happy Valley Loop" | "Eastbound/Westbound";

export interface LocalizedText {
  en: string;
  zhHK: string;
  zhCN: string;
}

export interface StationInfo {
  en: string;
  locCode: string;
  type: StationType;
  direction: StationDirection;
  zhHK: string;
  zhCN: string;
  district: LocalizedText;
  latitude?: number;
  longitude?: number;
}

export const ALL_STATIONS: StationInfo[] = stationsData as StationInfo[];

export function stationByLocCode(locCode: string): StationInfo {
  const info = ALL_STATIONS.find((s) => s.locCode === locCode);
  if (!info) {
    throw new Error(`Unknown station: ${locCode}`);
  }
  return info;
}

export function stationName(info: LocalizedText, locale: string): string {
  if (locale === "zh-HK") return info.zhHK;
  if (locale === "zh-CN") return info.zhCN;
  return info.en;
}

