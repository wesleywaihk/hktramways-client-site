export function stationByLocCode(locCode: string): StationInfo {
  const info = ALL_STATIONS.find((s) => s.locCode === locCode);
  if (!info) {
    throw new Error(`Unknown station: ${locCode}`);
  }
  return info;
}

export function stationName(info: StationInfo, locale: string): string {
  if (locale === "zh-HK") return info.zhHK;
  if (locale === "zh-CN") return info.zhCN;
  return info.en;
}

